/**
 * Retrieve nearby/adjacent districts for any given district ID or Name
 */
export function getNearbyDistricts(districtIdOrName: string): NearbyPlaceDetail[] {
  if (!districtIdOrName) return [];
  const key = districtIdOrName.toLowerCase().replace(/[^a-z]/g, '');

  // Exact key lookup
  if (ODISHA_NEARBY_DISTRICTS[key]) {
    return ODISHA_NEARBY_DISTRICTS[key];
  }

  // Partial key match
  const matchingKey = Object.keys(ODISHA_NEARBY_DISTRICTS).find(
    (k) => key.includes(k) || k.includes(key)
  );

  return matchingKey ? ODISHA_NEARBY_DISTRICTS[matchingKey] : [];
}
